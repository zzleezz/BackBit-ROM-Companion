"""Dark / Light theme manager: palettes, semantic colour tokens, the global stylesheet and live switching.

How theming works
-----------------
* ``COLORS`` (and ``LEVEL_COLORS``) are module-level dicts that are **updated in place** when the theme changes,
  so every ``from ui.widgets import COLORS`` sees the active palette. Painters and HTML renderers read them at
  draw time.
* Widgets never hard-code colours in ``setStyleSheet``. They get a **style role** (``set_role(w, "muted")``)
  and the global QSS, regenerated by :func:`apply`, styles every role. Switching therefore restyles the whole
  application instantly with no restart.
* Widgets that bake colours into rich text or ``QTableWidgetItem`` colours connect to ``manager.changed`` and
  re-render themselves.
"""

