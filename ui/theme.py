def palette(c: dict[str, str] | None = None) -> QPalette:
    c = c or COLORS
    pal = QPalette()
    roles = {
        QPalette.ColorRole.Window: c["bg"], QPalette.ColorRole.WindowText: c["text"],
        QPalette.ColorRole.Base: c["panel"], QPalette.ColorRole.AlternateBase: c["panel2"],
        QPalette.ColorRole.ToolTipBase: c["panel2"], QPalette.ColorRole.ToolTipText: c["text"],
        QPalette.ColorRole.Text: c["text"], QPalette.ColorRole.Button: c["panel2"],
        QPalette.ColorRole.ButtonText: c["text"], QPalette.ColorRole.BrightText: c["error"],
        QPalette.ColorRole.Link: c["info"], QPalette.ColorRole.Highlight: c["accent"],
        QPalette.ColorRole.HighlightedText: c["on_accent"], QPalette.ColorRole.PlaceholderText: c["muted"],
    }
    for role, color in roles.items():
        pal.setColor(role, QColor(color))
    for role in (QPalette.ColorRole.Text, QPalette.ColorRole.ButtonText, QPalette.ColorRole.WindowText):
        pal.setColor(QPalette.ColorGroup.Disabled, role, QColor(c["disabled"]))
    return pal


def apply(app: QApplication, name: str) -> str:
    """Switch the whole application to ``name`` ("dark" / "light") instantly. Returns the applied theme."""
    global _current
    name = normalize(name)
    _current = name
    COLORS.clear()
    COLORS.update(PALETTES[name])
    _sync_levels()
    app.setStyle("Fusion")
    app.setPalette(palette())
    app.setStyleSheet(stylesheet())
    manager.changed.emit(name)
    return name
