class _ThemeManager(QObject):
    changed = pyqtSignal(str)


manager = _ThemeManager()


def current() -> str:
    return _current


def normalize(name: str | None) -> str:
    return name if name in THEMES else DEFAULT_THEME


def other(name: str | None = None) -> str:
    return LIGHT if normalize(name or _current) == DARK else DARK


def _luminance(color: str) -> float:
    """WCAG 2 relative luminance."""
    c = QColor(color)

    def lin(v: float) -> float:
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4

    return 0.2126 * lin(c.redF()) + 0.7152 * lin(c.greenF()) + 0.0722 * lin(c.blueF())


def contrast_ratio(fg: str, bg: str) -> float:
    """WCAG contrast ratio (1..21) between two colours."""
    a, b = sorted((_luminance(fg), _luminance(bg)), reverse=True)
    return (a + 0.05) / (b + 0.05)


def contrast_text(color: str) -> str:
    """Black or white - whichever has the higher contrast ratio on ``color``."""
    return "#000000" if contrast_ratio("#000000", color) >= contrast_ratio("#ffffff", color) else "#ffffff"


# --------------------------------------------------------------------------- roles
def set_role(widget: QWidget, role: str, **props: str) -> QWidget:
    """Attach a style role (and optional state properties) and re-polish so the QSS applies immediately."""
    widget.setProperty("role", role)
    for k, v in props.items():
        widget.setProperty(k, v)
    repolish(widget)
    return widget


def set_state(widget: QWidget, **props: str) -> None:
    for k, v in props.items():
        widget.setProperty(k, v)
    repolish(widget)


def repolish(widget: QWidget) -> None:
    style = widget.style()
    style.unpolish(widget)
    style.polish(widget)
    widget.update()


BANNER_KINDS = ("identical", "content_match", "different_small", "different", "empty")


def banner_colors(kind: str) -> tuple[str, str]:
    bg = {"identical": COLORS["ok"], "content_match": COLORS["info"], "different_small": COLORS["warn"],
          "different": COLORS["error"], "empty": COLORS["panel2"]}[kind]
    if _current == LIGHT and kind != "empty":
        # saturated fills, as in dark mode, so the verdict still "pops" on a light window
        bg = {"identical": "#2fbf6a", "content_match": "#3aa9e0", "different_small": "#f2b705",
              "different": "#e5484d"}[kind]
    fg = COLORS["muted"] if kind == "empty" else contrast_text(bg)
    return bg, fg


